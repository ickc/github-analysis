#!/usr/bin/env python3
"""Compare reference and generated Actions metrics CSVs.

This script compares a reference metrics snapshot against CSVs generated by
`github-analysis`.

It intentionally distinguishes three kinds of differences:
1. Expected visibility drift: the reference snapshot contains private/deleted
   repos (for example `Repository not found`) or repos that are no longer
   visible to the token used for the fresh API fetch.
2. Expected snapshot drift: matched rows whose counts changed because more runs
   happened after the reference snapshot was exported.
3. Unexpected structural mismatches: missing generated files or shared rows that
   disappear even though the repo is still visible today.

Usage:
    python compare.py <reference_dir> <generated_dir>
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

import pandas as pd

SCHEMA = {
    "actions-usage-metrics": {
        "workflows": (
            ["Workflow", "Source repository", "Runner type", "Runtime OS"],
            ["Total minutes", "Workflow runs", "Jobs"],
        ),
        "jobs": (
            ["Job", "Workflow", "Source repository", "Runner type", "Runner labels"],
            ["Total minutes", "Job runs"],
        ),
        "repositories": (
            ["Source repository"],
            ["Total minutes", "Workflow runs", "Workflows"],
        ),
        "runtime-os": (
            ["Runtime OS"],
            ["Total minutes", "Workflow runs", "Workflows"],
        ),
        "runner-type": (
            ["Runner type"],
            ["Total minutes", "Workflow runs", "Workflows"],
        ),
    },
    "actions-performance-metrics": {
        "workflows": (
            ["Workflow", "Source repository"],
            ["Has job failures", "Avg run time", "Workflow runs", "Jobs"],
        ),
        "jobs": (
            ["Job", "Workflow", "Source repository", "Runner type", "Runner labels"],
            ["Failure rate", "Avg run time", "Avg queue time", "Job runs"],
        ),
        "repositories": (
            ["Source repository"],
            ["Failure rate", "Avg job run time", "Avg job queue time", "Job runs"],
        ),
        "runtime-os": (
            ["Runtime OS"],
            ["Failure rate", "Avg job run time", "Avg job queue time", "Job runs"],
        ),
        "runner-type": (
            ["Runner type"],
            ["Failure rate", "Avg job run time", "Avg job queue time", "Job runs"],
        ),
    },
}

ROUND = {
    "Total minutes": 0,
    "Workflow runs": 0,
    "Job runs": 0,
    "Jobs": 0,
    "Workflows": 0,
    "Has job failures": 2,
    "Failure rate": 2,
}

TIME_COLUMNS = {
    "Avg run time",
    "Avg queue time",
    "Avg job run time",
    "Avg job queue time",
}

COUNT_COLUMNS = {
    "Total minutes",
    "Workflow runs",
    "Job runs",
    "Jobs",
    "Workflows",
}

GREEN = "\033[92m"
YELLOW = "\033[93m"
RED = "\033[91m"
BOLD = "\033[1m"
RESET = "\033[0m"


def color(text: str, code: str) -> str:
    return f"{code}{text}{RESET}"


def clean_cell(value: object) -> object:
    """Strip GitHub's awkward CSV quoting from UI-exported snapshots."""
    if isinstance(value, str):
        value = re.sub(r'^"\'', "", value)
        value = re.sub(r'"$', "", value)
    return value


def load_reference(path: Path) -> pd.DataFrame:
    df = pd.read_csv(path)
    df.columns = [clean_cell(col) for col in df.columns]
    return df.apply(lambda col: col.map(clean_cell))


def load_generated(path: Path) -> pd.DataFrame:
    df = pd.read_csv(path)
    df.columns = [clean_cell(col) for col in df.columns]
    return df.apply(lambda col: col.map(clean_cell))


def normalize(df: pd.DataFrame, keys: list[str], numeric_cols: list[str]) -> pd.DataFrame:
    df = df.copy()
    for col in keys:
        if col in df.columns:
            df[col] = df[col].astype(str).str.strip()
    for col in numeric_cols:
        if col not in df.columns:
            continue
        numeric = pd.to_numeric(df[col], errors="coerce")
        if col in TIME_COLUMNS:
            # GitHub's exported timings are effectively stable at the second
            # level. Comparing whole milliseconds is just noise.
            df[col] = (numeric / 1000.0).round()
        else:
            df[col] = numeric.round(ROUND.get(col, 2))
    return df


def visible_repos(generated_dir: Path) -> set[str]:
    repos_path = generated_dir / "actions-usage-metrics" / "repositories.csv"
    if not repos_path.exists():
        return set()
    df = pd.read_csv(repos_path)
    if "Source repository" not in df.columns:
        return set()
    return set(df["Source repository"].astype(str).str.strip())


def repo_column(keys: list[str]) -> str | None:
    return "Source repository" if "Source repository" in keys else None


def compare_table(
    ref_path: Path,
    gen_path: Path,
    keys: list[str],
    numeric_cols: list[str],
    current_repos: set[str],
) -> tuple[bool, bool]:
    """Compare one table.

    Returns:
        structurally_ok: False only for missing generated data or shared rows
            unexpectedly disappearing while their repo is still visible.
        has_snapshot_drift: True when matched rows differ numerically or when
            rows appear/disappear for expected visibility/time reasons.
    """
    if not gen_path.exists():
        print(color(f"  MISSING generated file: {gen_path}", RED))
        return False, False

    ref = normalize(load_reference(ref_path), keys, numeric_cols)
    gen = normalize(load_generated(gen_path), keys, numeric_cols)

    if not all(key in ref.columns for key in keys) or not all(key in gen.columns for key in keys):
        print(color("  key columns do not line up; cannot compare this table", RED))
        return False, False

    cols_ref = [col for col in keys + numeric_cols if col in ref.columns]
    cols_gen = [col for col in keys + numeric_cols if col in gen.columns]
    merged = ref[cols_ref].merge(
        gen[cols_gen],
        on=keys,
        how="outer",
        suffixes=("_ref", "_gen"),
        indicator=True,
    )

    both = merged[merged["_merge"] == "both"].copy()
    only_ref = merged[merged["_merge"] == "left_only"].copy()
    only_gen = merged[merged["_merge"] == "right_only"].copy()

    repo_col = repo_column(keys)
    expected_missing = pd.DataFrame(columns=only_ref.columns)
    unexpected_missing = only_ref
    if repo_col is not None and not only_ref.empty:
        repo_values = only_ref[repo_col].astype(str)
        mask = repo_values.eq("Repository not found") | ~repo_values.isin(current_repos)
        expected_missing = only_ref[mask].copy()
        unexpected_missing = only_ref[~mask].copy()

    row_delta_flags = pd.DataFrame(index=both.index)
    count_drift = pd.Series(False, index=both.index)
    timing_drift = pd.Series(False, index=both.index)
    per_column = []
    for col in numeric_cols:
        rc = f"{col}_ref"
        gc = f"{col}_gen"
        if rc not in both.columns or gc not in both.columns:
            continue
        delta = (both[rc] - both[gc]).abs()
        row_delta_flags[col] = delta
        exact = int((delta == 0).sum())
        max_delta = float(delta.max()) if len(delta) else 0.0
        median_delta = float(delta.median()) if len(delta) else 0.0
        per_column.append((col, exact, len(delta), median_delta, max_delta))
        if col in COUNT_COLUMNS:
            count_drift = count_drift | delta.gt(0)
        else:
            timing_drift = timing_drift | delta.gt(0)

    exact_rows = int((~count_drift & ~timing_drift).sum()) if len(both) else 0
    timing_only_rows = int((~count_drift & timing_drift).sum()) if len(both) else 0
    count_drift_rows = int(count_drift.sum()) if len(both) else 0

    status = "MATCH"
    color_code = GREEN
    if not unexpected_missing.empty:
        status = "STRUCTURAL DIFF"
        color_code = RED
    elif not expected_missing.empty or not only_gen.empty or count_drift_rows or timing_only_rows:
        status = "COMPATIBLE WITH DRIFT"
        color_code = YELLOW

    print(
        f"  {color(status, color_code)}  "
        f"shared={len(both)}  exact={exact_rows}  "
        f"timing-only={timing_only_rows}  count-drift={count_drift_rows}  "
        f"ref-only(expected)={len(expected_missing)}  ref-only(unexpected)={len(unexpected_missing)}  "
        f"gen-only={len(only_gen)}"
    )

    if not expected_missing.empty and repo_col is not None:
        repos = sorted(set(expected_missing[repo_col].astype(str)))[:5]
        print(
            color(
                "  expected reference-only rows come from repos not visible today: "
                + ", ".join(repos),
                YELLOW,
            )
        )

    if not unexpected_missing.empty:
        print(color("  shared repo rows missing from generated output:", RED))
        print(unexpected_missing[keys].head(5).to_string(index=False, justify="left"))

    if not only_gen.empty:
        print(color("  generated-only rows are expected when newer runs exist today.", YELLOW))

    interesting_cols = [item for item in per_column if item[2] and item[0] in numeric_cols]
    if interesting_cols:
        print("  numeric overlap after normalization:")
        for col, exact, total, median_delta, max_delta in interesting_cols:
            print(
                f"    {col}: exact={exact}/{total} "
                f"median_delta={median_delta:g} max_delta={max_delta:g}"
            )

    structurally_ok = unexpected_missing.empty
    has_snapshot_drift = bool(
        len(expected_missing) or len(only_gen) or count_drift_rows or timing_only_rows
    )
    return structurally_ok, has_snapshot_drift


def main(reference_dir: Path, generated_dir: Path) -> int:
    current_repos = visible_repos(generated_dir)
    structural_ok = True
    drift_seen = False

    for metric, tables in SCHEMA.items():
        print(f"\n{color(metric, BOLD)}")
        for table_name, (keys, numeric_cols) in tables.items():
            ref_path = reference_dir / metric / f"{table_name}.csv"
            gen_path = generated_dir / metric / f"{table_name}.csv"
            if not ref_path.exists():
                print(f"  {table_name}: {color('SKIP (no reference file)', YELLOW)}")
                continue
            print(f"  {table_name}:")
            ok, drift = compare_table(ref_path, gen_path, keys, numeric_cols, current_repos)
            structural_ok = structural_ok and ok
            drift_seen = drift_seen or drift

    print()
    if structural_ok and not drift_seen:
        print(color("All tables match after normalization.", GREEN))
        return 0
    if structural_ok:
        print(color("Tables are structurally compatible; remaining differences are snapshot drift.", YELLOW))
        print("Reference-only rows come from hidden/removed repos, and shared-row deltas reflect newer runs.")
        return 0

    print(color("Unexpected structural differences remain.", RED))
    print("Those rows disappeared even though their repositories are still visible today.")
    return 1


if __name__ == "__main__":
    if len(sys.argv) != 3:
        print(f"Usage: {sys.argv[0]} <reference_dir> <generated_dir>")
        sys.exit(1)
    sys.exit(main(Path(sys.argv[1]), Path(sys.argv[2])))
